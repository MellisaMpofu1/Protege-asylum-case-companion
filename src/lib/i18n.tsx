const DICTS: Record<Locale, Dict> = { en, "pt-PT": pt };
export const LOCALES: { code: Locale; label: string }[] = [
  { code: "en", label: "English" },
  { code: "pt-PT", label: "Português (Portugal)" },
];
export const POLICY_VERSION = "2026-10-v1";

type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (k: TKey, vars?: Record<string, string>) => string;
  fDate: (v: string | null | undefined) => string | null;
  fInstant: (v: string | null | undefined) => string | null;
};
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("protege.locale");
    if (saved === "en" || saved === "pt-PT") setLocaleState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    window.localStorage.setItem("protege.locale", l);
  }, []);
  const value = useMemo<Ctx>(() => {
    const d = DICTS[locale];
    return {
      locale,
      setLocale,
      t: (k, vars) => {
        let s = d[k] ?? en[k] ?? k;
        if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, b);
        return s;
      },
      fDate: (v) => formatDateOnly(v, locale),
      fInstant: (v) => formatInstant(v, locale),
    };
  }, [locale, setLocale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  // Fall back to English if rendered outside the provider (e.g. during a hot reload).
  return useContext(I18nContext) ?? FALLBACK;
}

export const dictionaries = DICTS;

const FALLBACK: Ctx = {
  locale: "en",
  setLocale: () => {},
  t: (k, vars) => {
    let s = en[k] ?? k;
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, b);
    return s;
  },
  fDate: (v) => formatDateOnly(v, "en"),
  fInstant: (v) => formatInstant(v, "en"),
};
